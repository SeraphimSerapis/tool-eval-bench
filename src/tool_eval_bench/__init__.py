"""tool_eval_bench package."""

__all__ = ["__version__", "run_benchmark"]


def _resolve_version() -> str:
    """Report the version of the code actually running.

    ``_version.py`` is generated by setuptools-scm at build time and is the most
    precise source (it carries the commit for non-release builds).  Installed
    distribution metadata is the fallback, and a bare source tree with no build
    step at all reports an explicitly unknown version rather than pretending to
    be a release.
    """
    try:
        from tool_eval_bench._version import version

        return str(version)
    except ImportError:
        pass
    from importlib.metadata import PackageNotFoundError
    from importlib.metadata import version as _dist_version

    try:
        return _dist_version("tool-eval-bench")
    except PackageNotFoundError:
        return "0.0.0+unknown"


__version__ = _resolve_version()


async def run_benchmark(**kwargs):
    """Convenience re-export — see :func:`tool_eval_bench.api.run_benchmark`.

    This is an async function; call it with ``await`` or wrap in
    ``asyncio.run(run_benchmark(...))``.
    """
    from tool_eval_bench.api import run_benchmark as _run

    return await _run(**kwargs)
