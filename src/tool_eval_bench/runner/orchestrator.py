async def run_scenario(
    adapter: BackendAdapter,
    *,
    model: str,
    base_url: str,
    api_key: str | None,
    scenario: ScenarioDefinition,
    max_turns: int = MAX_TURNS,
    timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS,
    temperature: float = 0.0,
    seed: int | None = None,
    reference_date: str | None = None,
    reference_day: str | None = None,
    error_rate: float = 0.0,
    extra_params: dict[str, Any] | None = None,
    context_pressure_messages: list[ChatMessage] | None = None,
) -> ScenarioResult:
    """Run a single scenario through the multi-turn orchestration loop."""
    t0 = time.perf_counter()
    state = ScenarioState()
    # Meta must match the reference date actually injected into the prompt:
    # _initial_messages falls back to the benchmark default when None.
    state.meta["reference_date"] = reference_date or BENCHMARK_REFERENCE_DATE
    state.meta["reference_day"] = reference_day or BENCHMARK_REFERENCE_DAY
    messages = _initial_messages(
        scenario.user_message,
        reference_date=reference_date,
        reference_day=reference_day,
        context_pressure_messages=context_pressure_messages,
        scenario_id=scenario.id,
    )
    # None → use defaults; [] → explicitly no tools
    scenario_tools = UNIVERSAL_TOOLS if scenario.tools_override is None else scenario.tools_override
    scenario_tool_choice = scenario.tool_choice_override or "auto"
    # Per-scenario budget overrides the global max_turns for deep workflows
    # (e.g. TC-46) without raising the default for every scenario.
    if scenario.max_turns_override is not None:
        max_turns = scenario.max_turns_override
    available_tool_names = [
        str(tool.get("function", {}).get("name", "?")) for tool in (scenario_tools or [])
    ]
    trace_lines: list[str] = [
        "assistant=starting",
        f"available_tools={', '.join(available_tool_names) if available_tool_names else '(none)'}",
    ]
    if available_tool_names:
        trace_lines.append(f"tool_choice={scenario_tool_choice}")

    # Per-scenario seeded RNG for deterministic error injection.
    # Uses a stable digest offset so each scenario gets a unique
    # but reproducible injection pattern regardless of execution order.
    error_rng: random.Random | None = None
    if seed is not None and error_rate > 0:
        error_rng = random.Random(seed + _scenario_seed_offset(scenario.id))

    ttft_ms: float | None = None
    turn_latencies: list[float] = []
    total_prompt_tokens: int = 0
    total_completion_tokens: int = 0
    total_arg_bytes: int = 0  # Track tool call argument sizes
    parallel_tool_turns: list[int] = []
    state_checkpoints: list[str] = []

    # Build the queue of user messages: initial + any follow-ups
    follow_ups = list(scenario.follow_up_messages)  # copy so we can pop
    user_phase = 0  # which user message we're processing

    extra: dict[str, Any] = {}
    if seed is not None:
        extra["seed"] = seed
    if extra_params:
        extra.update(extra_params)
    if seed is not None:
        logger.debug(
            "seed=%d passed to server. Note: seed only controls logit sampling "
            "(greedy at temperature=0 is already deterministic). "
            "Full run-to-run reproducibility also requires stable server state, "
            "no concurrent requests, and consistent KV-cache configuration.",
            seed,
        )

    # True when the loop ends because the turn budget ran out before the model
    # produced a final answer (or before exhausting the follow-up queue).
    # Distinguishes turn-budget exhaustion from evaluator failures.
    budget_exhausted = True

    try:
        for turn in range(1, max_turns + 1):
            # Stream the first turn to measure TTFT accurately
            use_stream = turn == 1

            turn_start = time.perf_counter()
            # Only send response_format on content turns (not tool-calling
            # turns).  Many backends (llama.cpp, older vLLM) reject
            # response_format + tools in the same request.  When tools is
            # empty, response_format can be sent on turn 1 safely.
            response_format = scenario.response_format_override
            if response_format and scenario_tools and turn == 1 and not state.tool_calls:
                # First turn with tools — let the model make tool calls without
                # response_format constraint (re-applied on the content turn).
                response_format = None

            active_tool_choice = scenario_tool_choice
            if state.tool_calls and scenario.tool_choice_after_first_call is not None:
                active_tool_choice = scenario.tool_choice_after_first_call

            # Turns after the first are not streamed, so the read timeout bounds
            # the whole generation instead of the gap between tokens. Scale it
            # from what turn 1 actually took. See domain.timeouts.
            turn_timeout = (
                timeout_seconds
                if use_stream
                else unstreamed_turn_timeout(
                    timeout_seconds,
                    turn_latencies[0] if turn_latencies else 0.0,
                )
            )

            result = await adapter.chat_completion(
                model=model,
                messages=messages,
                tools=scenario_tools or None,  # Don't send empty list
                tool_choice=active_tool_choice if scenario_tools else None,
                temperature=temperature,
                max_tokens=4096,
                timeout_seconds=turn_timeout,
                api_key=api_key,
                base_url=base_url,
                extra_params=extra,
                stream=use_stream,
                response_format=response_format,
            )
            turn_ms = (time.perf_counter() - turn_start) * 1000
            turn_latencies.append(turn_ms)

            # A rejected request produced no model output, so there is nothing
            # to grade. Whether that is the model's fault depends on what the
            # request contained: once the model has authored a tool call, the
            # history carries arguments a strict server may refuse, and the
            # existing soft-result behaviour records that as a model failure.
            # Before then the request is entirely ours, so a 4xx means the
            # endpoint would not accept a parameter this benchmark sent
            # (tool_choice and response_format are the usual ones) and the
            # scenario measures the serving stack rather than the model.
            if result.transport_error_status is not None and not state.tool_calls:
                elapsed = time.perf_counter() - t0
                summary = (
                    f"Endpoint rejected the request with HTTP "
                    f"{result.transport_error_status} before the model produced anything: "
                    f"{result.content}"
                )
                trace_lines.append(f"transport_error={result.transport_error_status}")
                return ScenarioResult(
                    scenario_id=scenario.id,
                    status=ScenarioStatus.FAIL,
                    points=0,
                    summary=summary,
                    raw_log=_format_trace(
                        model, scenario, {"status": "fail", "summary": summary}, trace_lines
                    ),
                    duration_seconds=elapsed,
                    ttft_ms=ttft_ms,
                    turn_count=len(turn_latencies),
                    turn_latencies_ms=turn_latencies,
                    parallel_tool_turns=parallel_tool_turns,
                    state_checkpoints=state_checkpoints,
                    failure_kind=FailureKind.SERVER_ERROR,
                )

            # Capture TTFT from the first streamed turn
            if turn == 1 and result.ttft_ms is not None:
                ttft_ms = result.ttft_ms

            # Accumulate token usage
            if result.prompt_tokens is not None:
                total_prompt_tokens += result.prompt_tokens
            if result.completion_tokens is not None:
                total_completion_tokens += result.completion_tokens

            state.assistant_messages.append(result.content)
            state.assistant_reasoning.append(result.reasoning or "")
            phase_has_tool_calls = any(call.user_phase == user_phase for call in state.tool_calls)
            preserve_follow_up_reasoning = scenario.preserve_reasoning_across_follow_ups and bool(
                follow_ups
            )
            messages.append(
                _assistant_message(
                    result,
                    preserve_reasoning=phase_has_tool_calls or preserve_follow_up_reasoning,
                )
            )
            trace_lines.append(f"assistant_turn_{turn}={result.content or '[tool_calls_only]'}")
            if result.reasoning:
                trace_lines.append(f"assistant_reasoning_{turn}={result.reasoning}")

            # No tool calls → model finished this conversational phase
            if not result.tool_calls:
                # If there are follow-up user messages, inject the next one
                if follow_ups:
                    follow_up = follow_ups.pop(0)
                    user_phase += 1
                    messages.append({"role": "user", "content": follow_up})
                    trace_lines.append(f"user_follow_up_{user_phase}={follow_up}")
                    # Continue the loop — model will respond to the follow-up
                    continue

                # No more follow-ups → conversation is done
                state.final_answer = result.content
                budget_exhausted = False
                break

            tool_names = [tc.name for tc in result.tool_calls]
            trace_lines.append(f"tool_calls_requested={', '.join(tool_names)}")
            if len(result.tool_calls) > 1:
                parallel_tool_turns.append(turn)

            for tc in result.tool_calls:
                record = ToolCallRecord(
                    id=tc.id,
                    name=tc.name,
                    raw_arguments=tc.arguments_str,
                    arguments=tc.arguments,
                    turn=turn,
                    user_phase=user_phase,
                )
                state.tool_calls.append(record)
                total_arg_bytes += len(tc.arguments_str.encode("utf-8"))
                trace_lines.append(f"tool_call={record.name} {record.raw_arguments}")

                # Call the scenario's mock handler
                mock_result = scenario.handle_tool_call(state, record)

                # Error injection: randomly replace with simulated failure
                if error_rate > 0:
                    mock_result = _maybe_inject_error(
                        mock_result,
                        error_rate,
                        rng=error_rng,
                    )

                state.tool_results.append(
                    ToolResultRecord(call_id=record.id, name=record.name, result=mock_result)
                )
                trace_lines.append(f"tool_result={json.dumps(mock_result)}")
                messages.append(_tool_result_message(tc.id, tc.name, mock_result))
                if scenario.checkpoint:
                    diagnostic = scenario.checkpoint(state, record)
                    if diagnostic:
                        state_checkpoints.append(diagnostic)
                        state.meta.setdefault("state_checkpoints", []).append(diagnostic)
                        trace_lines.append(f"state_checkpoint={diagnostic}")

    except Exception as exc:
        elapsed = time.perf_counter() - t0
        summary = str(exc)
        trace_lines.append(f"error={summary}")
        return ScenarioResult(
            scenario_id=scenario.id,
            status=ScenarioStatus.FAIL,
            points=0,
            summary=summary,
            raw_log=_format_trace(
                model, scenario, {"status": "fail", "summary": summary}, trace_lines
            ),
            duration_seconds=elapsed,
            ttft_ms=ttft_ms,
            turn_count=len(turn_latencies),
            turn_latencies_ms=turn_latencies,
            parallel_tool_turns=parallel_tool_turns,
            state_checkpoints=state_checkpoints,
            failure_kind=_classify_runtime_error(exc),
        )

    # Ensure we have a final answer
    if not state.final_answer:
        state.final_answer = (
            state.assistant_messages[-1]
            if state.assistant_messages
            else "Model did not return a final answer."
        )
    trace_lines.append(f"final_answer={state.final_answer}")

    # Evaluate — wrapped in try/except so evaluator bugs don't crash the
    # entire benchmark run (issue #5).
    try:
        evaluation = scenario.evaluate(state)
    except Exception as eval_exc:
        import traceback

        tb_str = traceback.format_exc()
        logger.error("Evaluator error in scenario %s:\n%s", scenario.id, tb_str)
        elapsed = time.perf_counter() - t0
        summary = f"Evaluator error: {eval_exc}"
        trace_lines.append(f"eval_error={summary}\n{tb_str}")
        return ScenarioResult(
            scenario_id=scenario.id,
            status=ScenarioStatus.FAIL,
            points=0,
            summary=summary,
            raw_log=_format_trace(
                model, scenario, {"status": "fail", "summary": summary}, trace_lines
            ),
            duration_seconds=elapsed,
            ttft_ms=ttft_ms,
            turn_count=len(turn_latencies),
            turn_latencies_ms=turn_latencies,
            parallel_tool_turns=parallel_tool_turns,
            state_checkpoints=state_checkpoints,
            failure_kind=FailureKind.EVALUATOR_ERROR,
        )

    # Build diagnostic summary of what tools were actually called
    calls_made = [
        f"{tc.name}({', '.join(f'{k}={v}' for k, v in tc.arguments.items())})"
        for tc in state.tool_calls
    ]
    expected = scenario.description

    elapsed = time.perf_counter() - t0

    return ScenarioResult(
        scenario_id=scenario.id,
        status=evaluation.status,
        points=evaluation.points,
        summary=evaluation.summary,
        note=evaluation.note,
        raw_log=_format_trace(
            model,
            scenario,
            {
                "status": evaluation.status.value,
                "summary": evaluation.summary,
                "note": evaluation.note,
            },
            trace_lines,
        ),
        tool_calls_made=calls_made,
        expected_behavior=expected,
        duration_seconds=elapsed,
        ttft_ms=ttft_ms,
        turn_count=len(turn_latencies),
        turn_latencies_ms=turn_latencies,
        prompt_tokens=total_prompt_tokens,
        completion_tokens=total_completion_tokens,
        tool_call_arg_bytes=total_arg_bytes,
        parallel_tool_turns=parallel_tool_turns,
        state_checkpoints=state_checkpoints,
        failure_kind=(
            FailureKind.BUDGET_EXCEEDED
            if budget_exhausted and evaluation.status != ScenarioStatus.PASS
            else _classify_evaluation_failure(state, evaluation)
        ),
        # A turn-budget run-out is a distinct failure reason, not an evaluator
        # verdict: the model never reached a final answer / exhausted follow-ups.
        turn_budget_exceeded=budget_exhausted,
    )


