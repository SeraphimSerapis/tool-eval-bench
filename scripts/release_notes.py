#!/usr/bin/env python3
"""Print one release's section from CHANGELOG.md, for `gh release create --notes-file`.

CHANGELOG.md is generated by towncrier from the fragments in changelog.d/, so the
section for a tag already exists by the time a release is cut. This extracts it
verbatim rather than rewriting the notes by hand, which is how release notes and
changelog drift apart.

    scripts/release_notes.py 2.6.0 > /tmp/notes.md
    gh release create v2.6.0 --title "v2.6.0" --notes-file /tmp/notes.md
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CHANGELOG = Path(__file__).resolve().parent.parent / "CHANGELOG.md"


def extract(text: str, version: str) -> str:
    """Return the body of the `## [version] — date` section, without its heading."""
    heading = re.compile(r"^## \[([^\]]+)\]")
    lines = text.split("\n")

    start = None
    for i, line in enumerate(lines):
        match = heading.match(line)
        if match and match.group(1) == version:
            start = i
            break
    if start is None:
        found = [m.group(1) for m in (heading.match(x) for x in lines) if m]
        raise SystemExit(
            f"no section for version {version!r} in CHANGELOG.md. "
            f"Known versions: {', '.join(found[:8])}"
        )

    end = len(lines)
    for i in range(start + 1, len(lines)):
        if heading.match(lines[i]):
            end = i
            break

    return "\n".join(lines[start + 1 : end]).strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version", help="version to extract, without a leading v (e.g. 2.6.0)")
    parser.add_argument("--changelog", type=Path, default=CHANGELOG, help="path to CHANGELOG.md")
    args = parser.parse_args()

    version = args.version.lstrip("v")
    body = extract(args.changelog.read_text(encoding="utf-8"), version)
    if not body:
        raise SystemExit(f"section for {version} is empty")

    print(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
